// none.go - Build handler for modules with no build step (empty build_deps)
package builders

import (
	"io"

	core "github.com/ready-to-release/eac/contracts/core/0.1.0"
	build "github.com/ready-to-release/eac/contracts/runner/0.1.0/build"
)

// NoneHandler handles modules with no build step.
// Module types with empty build_deps include config files, templates, etc.
type NoneHandler struct{}

func (h *NoneHandler) Name() string { return "" }

func (h *NoneHandler) Capabilities() []string { return nil }

func (h *NoneHandler) Requirements() []string { return nil }

func (h *NoneHandler) ValidateModule(module core.ModuleContractPort, workspaceRoot, component string) error {
	return nil
}

// IsContainer returns false as this is a no-op handler.
func (h *NoneHandler) IsContainer() bool { return false }

// IsHostInstalled returns true as this is a no-op handler (no tool required).
func (h *NoneHandler) IsHostInstalled() bool { return true }

func (h *NoneHandler) ListArtifacts(module core.ModuleContractPort, workspaceRoot string) []string {
	return nil // No artifacts - manifest is generated by orchestrator
}

func (h *NoneHandler) Build(module core.ModuleContractPort, workspaceRoot, outputDir string, logWriter io.Writer, rawOpts any) int {
	Logln(logWriter, "\n=== No-op build: %s ===", module.GetMoniker())
	Logln(logWriter, "ℹ️  No build step required")
	return 0
}

var _ build.BuilderPort = (*NoneHandler)(nil)

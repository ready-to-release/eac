package content

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	eac "github.com/ready-to-release/eac/go/adapters/eac"
	"github.com/ready-to-release/eac/go/core/config"
	"gopkg.in/yaml.v3"
)

// CommandExecutor runs EAC commands and returns their output.
type CommandExecutor interface {
	Run(ctx context.Context, workspaceRoot string, args []string) (stdout string, err error)
}

// ToolCommandExecutor is the production implementation using the EAC adapter.
type ToolCommandExecutor struct{}

// Run executes an EAC command via the EAC adapter.
func (t ToolCommandExecutor) Run(ctx context.Context, workspaceRoot string, args []string) (string, error) {
	port := eac.New(workspaceRoot)
	result, err := port.Execute(ctx, args, &eac.ExecConfig{
		WorkspaceRoot: workspaceRoot,
		FullEnv:       append(os.Environ(), "NO_COLOR=1"),
	})
	if err != nil {
		return "", err
	}
	if !result.Success() {
		errMsg := string(result.Stderr)
		return "", fmt.Errorf("command failed (exit %d): %s", result.ExitCode, errMsg)
	}
	return string(result.Stdout), nil
}

// ExecuteCommands runs all command and inline sources.
// If fragmentsDir is non-empty, pre-built fragments are used exclusively (errors if missing).
// If fragmentsDir is empty, commands are executed directly.
// Returns a map of "target:marker" -> output for inline insertion.
func ExecuteCommands(
	ctx context.Context,
	book *config.Book,
	workspaceRoot, stagingDir string,
	executor CommandExecutor,
	logf func(string, ...any),
	fragmentsDir string,
) (map[string]string, error) {
	outputs := make(map[string]string)

	cmdSources := book.GetCommandSources()
	if len(cmdSources) > 0 {
		sort.Slice(cmdSources, func(i, j int) bool {
			return cmdSources[i].Order < cmdSources[j].Order
		})

		for i := range cmdSources {
			src := &cmdSources[i]

			if fragmentsDir != "" {
				// Use pre-built fragments exclusively
				fragmentPath := filepath.Join(fragmentsDir, src.Target)
				fragmentContent, err := os.ReadFile(fragmentPath)
				if err != nil {
					return nil, fmt.Errorf("pre-built fragment missing for '%s': %w", src.Target, err)
				}
				destPath := filepath.Join(stagingDir, src.Target)
				if err := os.MkdirAll(filepath.Dir(destPath), 0o755); err != nil {
					return nil, err
				}
				if err := os.WriteFile(destPath, fragmentContent, 0o644); err != nil {
					return nil, err
				}
				logf("    Used pre-built: %s", src.Target)
				continue
			}

			// Direct execution (no markdown-commands component configured)
			parts := strings.Fields(src.Command)
			if len(parts) == 0 {
				return nil, fmt.Errorf("empty command")
			}

			output, err := executor.Run(ctx, workspaceRoot, parts)
			if err != nil {
				return nil, fmt.Errorf("command '%s' failed: %w", src.Command, err)
			}

			content := FormatCommandOutput(*src, output)
			destPath := filepath.Join(stagingDir, src.Target)

			if err := os.MkdirAll(filepath.Dir(destPath), 0o755); err != nil {
				return nil, err
			}
			if err := os.WriteFile(destPath, []byte(content), 0o644); err != nil {
				return nil, err
			}

			logf("    Created: %s", src.Target)
		}
	}

	inlineSources := book.GetInlineSources()
	for i := range inlineSources {
		src := &inlineSources[i]
		for _, insert := range src.Inserts {
			parts := strings.Fields(insert.Command)
			if len(parts) == 0 {
				return nil, fmt.Errorf("empty inline command for marker '%s'", insert.Marker)
			}

			output, err := executor.Run(ctx, workspaceRoot, parts)
			if err != nil {
				return nil, fmt.Errorf("inline command '%s' for marker '%s' failed: %w",
					insert.Command, insert.Marker, err)
			}

			key := fmt.Sprintf("%s:%s", src.Target, insert.Marker)
			outputs[key] = strings.TrimSpace(output)
			logf("    Captured output for marker: %s", insert.Marker)
		}
	}

	return outputs, nil
}

// FormatCommandOutput adds frontmatter and generation metadata to command output.
func FormatCommandOutput(src config.Source, output string) string {
	var buf bytes.Buffer

	if len(src.Frontmatter) > 0 {
		buf.WriteString("---\n")
		frontmatterBytes, err := yaml.Marshal(src.Frontmatter)
		if err == nil {
			buf.Write(frontmatterBytes)
		} else {
			for k, v := range src.Frontmatter {
				buf.WriteString(fmt.Sprintf("%s: %v\n", k, v))
			}
		}
		buf.WriteString("---\n\n")
	}

	buf.WriteString(fmt.Sprintf("<!-- Generated by: %s -->\n", src.Command))
	buf.WriteString(fmt.Sprintf("<!-- Generated at: %s -->\n\n", time.Now().Format(time.RFC3339)))
	buf.WriteString(strings.TrimSpace(output))
	buf.WriteString("\n")

	return buf.String()
}

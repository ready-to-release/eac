func TestFormatCommandOutput_WithFrontmatter(t *testing.T) {
	src := config.Source{
		Command: "show modules",
		Target:  "reference/modules.md",
		Frontmatter: map[string]any{
			"title": "Modules",
		},
	}

	output := "# Module List\n\n| Name | Version |\n|------|---------|"

	result := FormatCommandOutput(src, output)

	assert.True(t, strings.HasPrefix(result, "---\n"))
	assert.Contains(t, result, "title: Modules")
	assert.Contains(t, result, "---\n\n<!-- Generated by: show modules -->")
	assert.Contains(t, result, "# Module List")
}

func TestFormatCommandOutput_WithoutFrontmatter(t *testing.T) {
	src := config.Source{
		Command: "show deps",
		Target:  "reference/deps.md",
	}

	output := "Some output"
	result := FormatCommandOutput(src, output)

	assert.False(t, strings.HasPrefix(result, "---\n"))
	assert.Contains(t, result, "<!-- Generated by: show deps -->")
	assert.Contains(t, result, "Some output")
}

func TestFormatCommandOutput_HasTimestamp(t *testing.T) {
	src := config.Source{
		Command: "test",
		Target:  "test.md",
	}

	before := time.Now().Add(-time.Second)
	result := FormatCommandOutput(src, "output")
	after := time.Now().Add(time.Second)

	// Verify the timestamp is present and reasonable
	assert.Contains(t, result, "<!-- Generated at: ")

	// Parse and verify the timestamp is between before and after
	parts := strings.Split(result, "<!-- Generated at: ")
	assert.Len(t, parts, 2)
	tsEnd := strings.Index(parts[1], " -->")
	assert.Greater(t, tsEnd, 0)
	ts, err := time.Parse(time.RFC3339, parts[1][:tsEnd])
	assert.NoError(t, err)
	assert.True(t, ts.After(before) || ts.Equal(before))
	assert.True(t, ts.Before(after) || ts.Equal(after))
}

func TestFormatCommandOutput_TrimsOutput(t *testing.T) {
	src := config.Source{
		Command: "test",
		Target:  "test.md",
	}

	result := FormatCommandOutput(src, "\n  Some output  \n\n")

	assert.Contains(t, result, "Some output")
	assert.True(t, strings.HasSuffix(result, "Some output\n"))
}

// mockExecutor records calls and returns configured output.
type mockExecutor struct {
	calls  [][]string
	output string
	err    error
}

func (m *mockExecutor) Run(_ context.Context, _ string, args []string) (string, error) {
	m.calls = append(m.calls, args)
	return m.output, m.err
}

func noopLog(string, ...any) {}

func TestExecuteCommands_FragmentsDirNonEmpty_UsesFragmentsExclusively(t *testing.T) {
	// Setup: create fragments dir with a pre-built fragment
	tmpDir := t.TempDir()
	fragmentsDir := filepath.Join(tmpDir, "fragments")
	stagingDir := filepath.Join(tmpDir, "staging")
	require.NoError(t, os.MkdirAll(filepath.Join(fragmentsDir, "reference"), 0o755))
	require.NoError(t, os.WriteFile(
		filepath.Join(fragmentsDir, "reference/modules.md"),
		[]byte("# Pre-built modules content"),
		0o644,
	))

	book := &config.Book{
		Sources: []config.Source{
			{Type: "command", Command: "show modules", Target: "reference/modules.md"},
		},
	}

	exec := &mockExecutor{output: "should not be called"}

	outputs, err := ExecuteCommands(context.Background(), book, tmpDir, stagingDir, exec, noopLog, fragmentsDir)
	require.NoError(t, err)
	assert.Empty(t, outputs) // command sources don't produce inline outputs

	// Verify fragment was copied to staging
	content, err := os.ReadFile(filepath.Join(stagingDir, "reference/modules.md"))
	require.NoError(t, err)
	assert.Equal(t, "# Pre-built modules content", string(content))

	// Verify executor was NOT called (fragments-only mode)
	assert.Empty(t, exec.calls, "executor should not be called when fragments are available")
}

func TestExecuteCommands_FragmentsDirNonEmpty_ErrorsOnMissingFragment(t *testing.T) {
	// Setup: create fragments dir WITHOUT the expected fragment
	tmpDir := t.TempDir()
	fragmentsDir := filepath.Join(tmpDir, "fragments")
	stagingDir := filepath.Join(tmpDir, "staging")
	require.NoError(t, os.MkdirAll(fragmentsDir, 0o755))

	book := &config.Book{
		Sources: []config.Source{
			{Type: "command", Command: "show modules", Target: "reference/modules.md"},
		},
	}

	exec := &mockExecutor{output: "should not be called"}

	_, err := ExecuteCommands(context.Background(), book, tmpDir, stagingDir, exec, noopLog, fragmentsDir)
	require.Error(t, err)
	assert.Contains(t, err.Error(), "pre-built fragment missing")
	assert.Contains(t, err.Error(), "reference/modules.md")

	// Verify executor was NOT called
	assert.Empty(t, exec.calls, "executor should not be called in fragments-only mode")
}

func TestExecuteCommands_EmptyFragmentsDir_ExecutesDirectly(t *testing.T) {
	tmpDir := t.TempDir()
	stagingDir := filepath.Join(tmpDir, "staging")

	book := &config.Book{
		Sources: []config.Source{
			{Type: "command", Command: "show modules", Target: "reference/modules.md"},
		},
	}

	exec := &mockExecutor{output: "# Direct output"}

	outputs, err := ExecuteCommands(context.Background(), book, tmpDir, stagingDir, exec, noopLog, "")
	require.NoError(t, err)
	assert.Empty(t, outputs)

	// Verify executor WAS called
	require.Len(t, exec.calls, 1)
	assert.Equal(t, []string{"show", "modules"}, exec.calls[0])

	// Verify output was written to staging
	content, err := os.ReadFile(filepath.Join(stagingDir, "reference/modules.md"))
	require.NoError(t, err)
	assert.Contains(t, string(content), "# Direct output")
}

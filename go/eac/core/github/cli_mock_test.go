func TestCLIMock_CallTracking(t *testing.T) {
	mock := NewCLIMock().WithWorkflowRuns("ci.yml", []WorkflowRun{
		{ID: 123, HeadSHA: "abc", Status: "completed", Conclusion: "success"},
	})

	// Make several calls
	mock.Exec("run", "list", "-w", "ci.yml", "--json", "databaseId,headSha,status,conclusion,createdAt,name")
	mock.Exec("run", "list", "-w", "ci.yml", "--json", "databaseId,headSha,status,conclusion,createdAt,name")
	mock.Exec("release", "list", "--limit", "100", "--json", "tagName,name,isDraft")

	if len(mock.calls) != 3 {
		t.Errorf("expected 3 calls, got %d", len(mock.calls))
	}

	// Verify first call
	if mock.calls[0].Command != "run list" {
		t.Errorf("expected first command to be 'run list', got '%s'", mock.calls[0].Command)
	}

	// Verify last call
	if mock.calls[2].Command != "release list" {
		t.Errorf("expected last command to be 'release list', got '%s'", mock.calls[2].Command)
	}

	// Verify args
	if len(mock.calls[0].Args) < 3 {
		t.Error("expected args to be captured")
	}
}


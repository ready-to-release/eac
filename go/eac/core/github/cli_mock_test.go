func TestCLIMock_WithWorkflowRuns(t *testing.T) {
	runs := []WorkflowRun{
		{
			ID:         123456789,
			HeadSHA:    "abc123",
			Status:     "completed",
			Conclusion: "success",
			CreatedAt:  time.Now(),
			Name:       "CI",
		},
		{
			ID:         987654321,
			HeadSHA:    "def456",
			Status:     "in_progress",
			Conclusion: "",
			CreatedAt:  time.Now(),
			Name:       "CI",
		},
	}

	mock := NewCLIMock().WithWorkflowRuns("ci.yml", runs)

	// Execute the command that would be generated by GHClient
	output, err := mock.Exec("run", "list", "-w", "ci.yml", "--json", "databaseId,headSha,status,conclusion,createdAt,name")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	// Verify the output contains expected data
	outputStr := string(output)
	if !strings.Contains(outputStr, "abc123") {
		t.Error("expected output to contain 'abc123'")
	}
	if !strings.Contains(outputStr, "123456789") {
		t.Error("expected output to contain run ID 123456789")
	}
	if !strings.Contains(outputStr, "in_progress") {
		t.Error("expected output to contain 'in_progress'")
	}
}

func TestCLIMock_WithWorkflowRuns_MultipleWorkflows(t *testing.T) {
	mock := NewCLIMock().
		WithWorkflowRuns("ci.yml", []WorkflowRun{
			{ID: 111, HeadSHA: "sha1", Status: "completed", Conclusion: "success"},
		}).
		WithWorkflowRuns("release.yml", []WorkflowRun{
			{ID: 222, HeadSHA: "sha2", Status: "completed", Conclusion: "success"},
		})

	// CI workflow
	output, err := mock.Exec("run", "list", "-w", "ci.yml", "--json", "databaseId,headSha,status,conclusion,createdAt,name")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if !strings.Contains(string(output), "sha1") {
		t.Error("expected ci.yml output to contain sha1")
	}
	if strings.Contains(string(output), "sha2") {
		t.Error("expected ci.yml output to NOT contain sha2")
	}

	// Release workflow
	output, err = mock.Exec("run", "list", "-w", "release.yml", "--json", "databaseId,headSha,status,conclusion,createdAt,name")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if !strings.Contains(string(output), "sha2") {
		t.Error("expected release.yml output to contain sha2")
	}
	if strings.Contains(string(output), "sha1") {
		t.Error("expected release.yml output to NOT contain sha1")
	}
}


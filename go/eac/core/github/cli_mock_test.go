func TestCLIMock_CommandNormalization(t *testing.T) {
	// Test that command matching works with various flag combinations
	mock := NewCLIMock().WithWorkflowRuns("ci.yml", []WorkflowRun{
		{ID: 123, HeadSHA: "abc", Status: "completed", Conclusion: "success"},
	})

	// These should all match the same command
	testCases := [][]string{
		{"run", "list", "-w", "ci.yml", "--json", "databaseId,headSha,status,conclusion,createdAt,name"},
		{"run", "list", "-w", "ci.yml", "--json", "databaseId,headSha,status,conclusion,createdAt,name", "-L", "10"},
		{"run", "list", "-w", "ci.yml", "--json", "databaseId,headSha,status,conclusion,createdAt,name", "-s", "success"},
	}

	for i, args := range testCases {
		output, err := mock.Exec(args...)
		if err != nil {
			t.Errorf("test case %d: unexpected error: %v", i, err)
		}
		if !strings.Contains(string(output), "abc") {
			t.Errorf("test case %d: expected output to contain 'abc'", i)
		}
	}
}


// none.go - Build handler for modules with no build step (empty build_deps)
package builders

import (
	"io"

	"github.com/ready-to-release/eac/go/eac/core/contracts/modules"
)

func init() {
	RegisterHandler(&NoneHandler{})
}

// NoneHandler handles modules with no build step.
// Module types with empty build_deps include config files, templates, etc.
type NoneHandler struct{}

func (h *NoneHandler) Name() string { return "" }

func (h *NoneHandler) Capabilities() []string { return nil }

func (h *NoneHandler) Requirements() []string { return nil }

func (h *NoneHandler) ValidateModule(module *modules.ModuleContract, workspaceRoot, component string) error {
	return nil
}

func (h *NoneHandler) ListArtifacts(module *modules.ModuleContract, workspaceRoot string) []string {
	return nil // No artifacts - manifest is generated by orchestrator
}

func (h *NoneHandler) Build(module *modules.ModuleContract, workspaceRoot, outputDir string, logWriter io.Writer, opts BuildOptions) int {
	Logln(logWriter, "\n=== No-op build: %s ===", module.Moniker)
	Logln(logWriter, "ℹ️  No build step required")
	return 0
}

package books

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/ready-to-release/eac/go/eac/core/config"
	"github.com/ready-to-release/eac/go/eac/core/repository"
	"gopkg.in/yaml.v3"
)

// executeCommands runs all command and inline sources (Step 2)
// Returns a map of "target:marker" -> output for inline insertion in Step 5
func (p *Preprocessor) executeCommands() (map[string]string, error) {
	outputs := make(map[string]string)

	// Execute command sources (write to files)
	cmdSources := p.book.GetCommandSources()
	if len(cmdSources) > 0 {
		// Sort by order field
		sort.Slice(cmdSources, func(i, j int) bool {
			return cmdSources[i].Order < cmdSources[j].Order
		})

		for _, src := range cmdSources {
			output, err := p.runCommand(src.Command)
			if err != nil {
				return nil, fmt.Errorf("command '%s' failed: %w", src.Command, err)
			}

			// Write to target file with frontmatter
			content := p.formatCommandOutput(src, output)
			destPath := filepath.Join(p.stagingDir, src.Target)

			if err := os.MkdirAll(filepath.Dir(destPath), 0755); err != nil {
				return nil, err
			}
			if err := os.WriteFile(destPath, []byte(content), 0644); err != nil {
				return nil, err
			}

			p.log("    Created: %s", src.Target)
		}
	}

	// Execute inline sources (store in memory for Step 5)
	inlineSources := p.book.GetInlineSources()
	for _, src := range inlineSources {
		for _, insert := range src.Inserts {
			output, err := p.runCommand(insert.Command)
			if err != nil {
				return nil, fmt.Errorf("inline command '%s' for marker '%s' failed: %w",
					insert.Command, insert.Marker, err)
			}

			// Store for Step 5 insertion
			key := fmt.Sprintf("%s:%s", src.Target, insert.Marker)
			outputs[key] = strings.TrimSpace(output)
			p.log("    Captured output for marker: %s", insert.Marker)
		}
	}

	return outputs, nil
}

// runCommand executes an EAC command and captures output
func (p *Preprocessor) runCommand(command string) (string, error) {
	// Parse command (e.g., "show modules" -> ["show", "modules"])
	parts := strings.Fields(command)
	if len(parts) == 0 {
		return "", fmt.Errorf("empty command")
	}

	// Use repository.CommandsBinaryPath() for the canonical binary location
	cmdBinary := repository.CommandsBinaryPath(p.workspaceRoot)

	cmd := exec.Command(cmdBinary, parts...)
	cmd.Dir = p.workspaceRoot

	// Set environment to ensure consistent output
	cmd.Env = append(os.Environ(), "NO_COLOR=1")

	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr

	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("%s: %s", err, stderr.String())
	}

	return stdout.String(), nil
}

// formatCommandOutput adds frontmatter and generation metadata to command output
func (p *Preprocessor) formatCommandOutput(src config.Source, output string) string {
	var buf bytes.Buffer

	// Add frontmatter if specified
	if len(src.Frontmatter) > 0 {
		buf.WriteString("---\n")

		// Use yaml.Marshal for proper formatting
		frontmatterBytes, err := yaml.Marshal(src.Frontmatter)
		if err == nil {
			buf.Write(frontmatterBytes)
		} else {
			// Fallback to simple key: value format
			for k, v := range src.Frontmatter {
				buf.WriteString(fmt.Sprintf("%s: %v\n", k, v))
			}
		}
		buf.WriteString("---\n\n")
	}

	// Add generation metadata as HTML comment
	buf.WriteString(fmt.Sprintf("<!-- Generated by: %s -->\n", src.Command))
	buf.WriteString(fmt.Sprintf("<!-- Generated at: %s -->\n\n", time.Now().Format(time.RFC3339)))

	// Add command output
	buf.WriteString(strings.TrimSpace(output))
	buf.WriteString("\n")

	return buf.String()
}
